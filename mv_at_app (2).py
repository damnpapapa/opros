HARM_SCALES = ["S1", "S2", "S3", "S4", "S5", "S6", "S7", "S8", "S9", "S10", "S11"]


def reverse_value(v: int) -> int:
    return 4 - v


def compute_scores(responses: dict[int, int]) -> dict:
    """Считает все Sᵢ, MVI и TDH из словаря {item_id: 0..4}."""
    subscores = {}
    for code, info in SUBSCALES.items():
        vals = []
        for item_id in info["items"]:
            v = responses[item_id]
            if item_id in REVERSE_IDS:
                v = reverse_value(v)
            vals.append(v)
        subscores[code] = float(np.mean(vals))
    mvi = float(np.mean([subscores[c] for c in HARM_SCALES]))
    s12 = subscores["S12"]
    tdh = (mvi * 11 + s12 * 2) / 13.0
    subscores["MVI"] = mvi
    subscores["TDH"] = tdh
    return subscores


def risk_level(tdh: float) -> tuple[str, str, str]:
    """→ (label, hex-color, описание)."""
    if tdh <= 1.0:
        return ("Низкий", "#2E7D32",
                "Медиапотребление хорошо интегрировано в жизнь. "
                "Шкалы уязвимости не выражены, благополучие в норме. "
                "Дополнительные интервенции не показаны.")
    if tdh <= 2.0:
        return ("Умеренный", "#F9A825",
                "Появляются отдельные «красные флаги». "
                "Имеет смысл обратить внимание на 2–3 субшкалы с самыми "
                "высокими значениями и поработать с ними точечно.")
    if tdh <= 3.0:
        return ("Повышенный", "#EF6C00",
                "Выраженный вклад медиапотребления в негативные психологические состояния. "
                "Рекомендуется поведенческая работа (digital boundaries, sleep hygiene) "
                "и оценка по клиническим шкалам (BDI, BSI и т.п.).")
    return ("Высокий", "#C62828",
            "Серьёзный риск. Картина может удовлетворять критериям "
            "проблемного использования соцсетей или сопутствующего расстройства. "
            "Рекомендована консультация специалиста.")


