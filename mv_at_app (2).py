def render_item(item_id: int, section: str, text: str):
    """Один пункт с радио-кнопками 0..4."""
    if section == "A":
        anchors = A_ANCHORS[item_id]
        options = [0, 1, 2, 3, 4]
        fmt = lambda v: f"{v} — {anchors[v]}"
    else:
        options = [0, 1, 2, 3, 4]
        fmt = lambda v: str(v)
    reverse_mark = " ⓡ" if item_id in REVERSE_IDS else ""
    label = f"**{item_id}.** {text}{reverse_mark}"
    val = st.radio(
        label, options,
        format_func=fmt,
        horizontal=True,
        key=f"item_{item_id}",
        index=None,
    )
    return val


def page_form():
    st.title("📱 Опросник")
    st.markdown(
        "**Шкала ответов:** 0 — совершенно не соответствует · 1 — скорее нет · "
        "2 — частично · 3 — скорее да · 4 — полностью соответствует. "
        "Пункты с пометкой ⓡ — обратного кодирования (мы пересчитаем их за вас)."
    )

    # Прогресс
    answered = sum(1 for k in st.session_state if k.startswith("item_")
                   and st.session_state[k] is not None)
    st.progress(answered / 52, text=f"Отвечено: {answered} / 52")
    st.divider()

    current_section = None
    for item_id, section, text in ITEMS:
        if section != current_section:
            current_section = section
            st.header(SECTION_TITLES[section])
        render_item(item_id, section, text)

    st.divider()
    col1, col2 = st.columns([1, 1])
    with col1:
        if st.button("← Назад", use_container_width=True):
            st.session_state.page = "intro"
            st.rerun()
    with col2:
        submit = st.button("Получить результаты →", type="primary",
                           use_container_width=True, disabled=answered < 52)
    if submit:
        responses = {item_id: st.session_state[f"item_{item_id}"]
                     for item_id, _, _ in ITEMS}
        st.session_state.responses = responses
        st.session_state.page = "results"
        st.rerun()
    elif answered < 52:
        st.warning(f"Чтобы получить результат, нужно ответить на все 52 пункта. "
                   f"Осталось: {52 - answered}.")


