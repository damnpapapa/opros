def radar_chart(scores: dict) -> plt.Figure:
    """Радар-диаграмма по 12 шкалам S1..S12 с цветными зонами риска."""
    codes = HARM_SCALES + ["S12"]
    labels = [SUBSCALES[c]["name"] for c in codes]
    # Сокращаем длинные подписи
    short = {
        "PSMU — проблемное использование": "PSMU",
        "FOMO": "FOMO",
        "Социальное сравнение": "Сравнение",
        "Импульсивность": "Импульсив.",
        "Непереносимость неопределённости": "Неопредел.",
        "Невротизм / эмоц. реактивность": "Невротизм",
        "Когнитивные ошибки": "Когнитив.\nошибки",
        "Я-концепция": "Я-концеп.",
        "Образ тела": "Образ тела",
        "Социальные последствия": "Соц. посл.",
        "Информационная уязвимость": "Информ.\nуязвим.",
        "Снижение благополучия (инверс. WHO-5)": "↓ Благопол.",
    }
    labels = [short.get(l, l) for l in labels]
    values = [scores[c] for c in codes]

    n = len(codes)
    angles = np.linspace(0, 2 * np.pi, n, endpoint=False).tolist()
    values_closed = values + [values[0]]
    angles_closed = angles + [angles[0]]

    fig, ax = plt.subplots(figsize=(7, 7), subplot_kw=dict(polar=True))

    # Цветные «кольца» рисков
    theta = np.linspace(0, 2 * np.pi, 200)
    for r_inner, r_outer, color in [
        (0, 1, "#C8E6C9"),     # низкий
        (1, 2, "#FFF59D"),     # умеренный
        (2, 3, "#FFCC80"),     # повышенный
        (3, 4, "#EF9A9A"),     # высокий
    ]:
        ax.fill_between(theta, r_inner, r_outer, color=color, alpha=0.35, zorder=0)

    ax.plot(angles_closed, values_closed, color="#1A237E", linewidth=2.2, zorder=3)
    ax.fill(angles_closed, values_closed, color="#3F51B5", alpha=0.25, zorder=2)
    ax.scatter(angles, values, color="#1A237E", s=40, zorder=4)

    ax.set_xticks(angles)
    ax.set_xticklabels(labels, fontsize=9)
    ax.set_yticks([1, 2, 3, 4])
    ax.set_yticklabels(["1", "2", "3", "4"], fontsize=8, color="#555")
    ax.set_ylim(0, 4)
    ax.set_rlabel_position(0)
    ax.grid(color="#BBB", linewidth=0.6)
    ax.spines["polar"].set_visible(False)
    ax.set_title("Профиль уязвимости по 12 шкалам (0–4)", fontsize=12, pad=20)
    plt.tight_layout()
    return fig


def bar_chart(scores: dict) -> plt.Figure:
    """Горизонтальные бары по 12 шкалам, окрашены в цвет уровня риска."""
    codes = HARM_SCALES + ["S12"]
    labels = [f"{c}: {SUBSCALES[c]['name']}" for c in codes]
    vals = [scores[c] for c in codes]
    colors = []
    for v in vals:
        if v <= 1: colors.append("#2E7D32")
        elif v <= 2: colors.append("#F9A825")
        elif v <= 3: colors.append("#EF6C00")
        else: colors.append("#C62828")

    fig, ax = plt.subplots(figsize=(8, 5.5))
    y = np.arange(len(codes))
    ax.barh(y, vals, color=colors, edgecolor="white", height=0.7)
    ax.set_yticks(y)
    ax.set_yticklabels(labels, fontsize=9)
    ax.set_xlim(0, 4)
    ax.set_xticks([0, 1, 2, 3, 4])
    ax.invert_yaxis()
    ax.axvline(1, color="#888", linewidth=0.6, linestyle="--")
    ax.axvline(2, color="#888", linewidth=0.6, linestyle="--")
    ax.axvline(3, color="#888", linewidth=0.6, linestyle="--")
    for spine in ["top", "right"]:
        ax.spines[spine].set_visible(False)
    ax.set_xlabel("Балл (0–4)", fontsize=10)
    ax.set_title("Балл по каждой субшкале", fontsize=12, pad=10)
    plt.tight_layout()
    return fig


