def identify_profile(scores: dict) -> dict:
    """Определяет профиль(и) по правилу: Sᵢ ≥ 2.5 И Sᵢ ≥ MVI + 0.5 → 'доминирующая'."""
    mvi = scores["MVI"]
    dominant = {
        code for code in HARM_SCALES + ["S12"]
        if scores[code] >= 2.5 and scores[code] >= mvi + 0.5
    }
    # Особый случай: «здоровый»
    if scores["TDH"] <= 1.0 and scores["S12"] <= 1.5:
        return {"primary": HEALTHY_PROFILE, "matches": [], "dominant": dominant}
    # Поиск совпадений с типовыми профилями
    matches = []
    for p in PROFILES:
        if p["required"].issubset(dominant):
            matches.append(p)
    if not matches:
        # Нет «чистого» профиля — общий риск
        generic = {
            "key": "diffuse",
            "name": "Диффузный паттерн",
            "description":
                "Нет одного выраженного доминирующего набора шкал. "
                "Уязвимость распределена сравнительно равномерно — это указывает "
                "на общий, а не специфический риск. Опирайтесь на интерпретацию по субшкалам ниже.",
            "recommendations": [
                "Выберите 2 субшкалы с самыми высокими баллами и работайте с ними по очереди",
                "Через 4–6 недель пройдите опросник снова, чтобы увидеть динамику",
            ],
        }
        return {"primary": generic, "matches": [], "dominant": dominant}
    primary = matches[0]
    return {"primary": primary, "matches": matches, "dominant": dominant}


